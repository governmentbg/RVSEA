        private async Task CheckDocumentId()
        {
            Guid? documentId = _documentId;
            if (documentId.HasValue)
            {
                ProcessKind processKind = RequireProcessKind();
                if (!await WebApiClientService.DocumentExists(processKind, documentId))
                {
                    throw new Exception($"В системата липсва {GetDocumentIdName()?.ToLower()} за {processKind}-{documentId}");
                }
            }
            else
            {
                throw new Exception($"Въведеният идентификатор на {GetDocumentIdName()} е невалиден!");
            }
        }

        private async Task CheckFileName(string fileName)
        {
            //string fileName = Path.GetFileName(fileNameTextBox.Text);
            if (await WebApiClientService.FileExists(GetProcessKind(), GetFileKind(), _documentId, _queueItemId, fileName))
            {
                throw new Exception($"В системата вече има качен или чакащ в опашката файл {GetProcessKind()}:{GetFileKind()}:{_documentId}:{_queueItemId}{Environment.NewLine}{fileName}");
            }
        }

        private async Task LoadMasterFilesForDocument()
        {
            //Console.WriteLine("LoadMasterFilesForDocument - begin");

            Guid? lastSelected = masterFileNameComboBox.SelectedItem != null ?
                ((CodeNameModel)masterFileNameComboBox.SelectedItem).Code : null;

            masterFileNameComboBox.DataSource = null;
            ProcessKind? processKind = GetProcessKind();
            if ((processKind == ProcessKind.Fund || processKind == ProcessKind.Ed) && _documentId != null)
            {
                CodeNameModel[] masterFiles = await WebApiClientService.MastersForDocument(_documentId);
                //masterFileNameComboBox.Items.AddRange(masterFiles);
                masterFileNameComboBox.DataSource = masterFiles;
                masterFileNameComboBox.ValueMember = nameof(CodeNameModel.Code);
                masterFileNameComboBox.DisplayMember = nameof(CodeNameModel.Name);

                CodeNameModel? item = masterFiles.Where(x => x.Code == lastSelected).FirstOrDefault();
                if (item != null)
                {
                    masterFileNameComboBox.SelectedItem = item;
                }
            }

            //Console.WriteLine("LoadMasterFilesForDocument - end");
        }

