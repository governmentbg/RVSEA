        private void LoadFileInfo()
        {
            if (InfoPanelVisible)
            {
                infoTextBox.Text = null;
                info2TextBox.Text = null;

                //string fileName = fileNameTextBox.Text;
                string fileName = (string)fileNamesListBox.SelectedItem;
                if (File.Exists(fileName))
                {
                    if (DAA.FileUtils.Consts.IsImageExtension(Path.GetExtension(fileName)))
                    {
                        pictureBox.ImageLocation = fileName;
                        pictureBox.LoadAsync();
                    }
                    else
                    {
                        pictureBox.Image = null;
                    }

                    info2TextBox.Text = MetadataUtil.GetFileMetadata(fileName);
                    if (pictureBox.Image == null && !string.IsNullOrEmpty(info2TextBox.Text))
                    {
                        infoTabControl.SelectedTab = info2TabPage;
                    }
                }
            }
            else
            {
                pictureBox.Image = null;
            }
        }

        private void pictureBox_LoadCompleted(object sender, AsyncCompletedEventArgs e)
        {
            infoTextBox.Text = MetadataUtil.GetImageDescription(pictureBox.Image);
        }

