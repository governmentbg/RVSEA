                errorProvider.SetError(masterFileIdPanel, "Изберете master файл, към който се прикача производен/демо!");
            }

            return result;
        }

        private async Task ValidateFile(string fileName)
        {
            if (Settings.AppSettings.ScanWithAntivirusClientApp)
            {
                try
                {
                    AntivirusUtil.Scan(fileName);
                }
                catch (Exception e)
                {
                    MessageBox.Show($"{e.GetType()}: {e.Message}");
                }
            }
            await ValidateUtil.ValidateFile(fileName, Settings.AppSettings);
        }

        private string GetValidationErrors()
        {
            List<string> errors = new();
            GetValidationErrorsHelp(this, errors);
            return string.Join(Environment.NewLine, errors);
        }

        private void GetValidationErrorsHelp(Control control, List<string> errors)
        {
            string error = errorProvider.GetError(control);
            if (!string.IsNullOrWhiteSpace(error))
            {
                errors.Add(error);
            }

            if (control.HasChildren)
            {
                foreach (Control child in control.Controls)
                {
                    GetValidationErrorsHelp(child, errors);
                }
            }
        }

        private async void okButton_Click(object sender, EventArgs e)
        {
            if (!await CustomValidate())
            {
                throw new Exception($"Грешки във въведените данни {Environment.NewLine}{GetValidationErrors()}");
                //return;
            }
            else
            {
                foreach (string fileName in FileNames)
                {
                    await ValidateFile(fileName);
                }

                DialogResult = DialogResult.OK;
            }

        }

