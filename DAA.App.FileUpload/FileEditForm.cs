                result = false;
                errorProvider.SetError(browseButton, "Изберете файл за качване!");
            }
            else
            {
                string errors = "";

                foreach (string fileName in FileNames)
                {
                    try
                    {
                        await CheckFileName(fileName);
                    }
                    catch (Exception e)
                    {
                        errors += $"{Environment.NewLine}{fileName}: {e.Message}";
                        fileNamesListBox.Items.Remove(fileName);
                    }
                }

                if (!string.IsNullOrEmpty(errors))
                {
                    result = false;
                    errors = "Грешки в следните файлове - премахнати са от списъка:" + errors;
                    errorProvider.SetError(browseButton, errors);
                }
            }

            //if (string.IsNullOrWhiteSpace(fileNameTextBox.Text))
            //{
            //    result = false;
            //    errorProvider.SetError(browseButton, "Изберете файл за качване!");
            //}
            //else if (!File.Exists(fileNameTextBox.Text))
            //{
            //    result = false;
            //    errorProvider.SetError(browseButton, $"Не е намерен файл с име {fileNameTextBox.Text}!");
            //}
            //else
            //{
            //    try
            //    {
            //        await CheckFileName();
            //    }
            //    catch (Exception e)
            //    {
            //        result = false;
            //        errorProvider.SetError(browseButton, e.Message);
            //    }
            //}



            if (!processKindFundRadioButton.Checked && !processKindEdRadioButton.Checked && !processKindKmfRadioButton.Checked && !processKindRawRadioButton.Checked)
            {
