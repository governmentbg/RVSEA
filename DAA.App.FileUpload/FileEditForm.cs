        public async Task LoadFromModel(QueueItemModel model)
        {
            _loading = true;

            _queueItemId = model.Id;

            documentIdTextBox.Text = model.DocumentId.ToString();
            //fileNameTextBox.Text = model.LocalFileName;
            fileNamesListBox.Items.Clear();
            fileNamesListBox.Items.Add(model.LocalFileName);
            //fileNamesListBox.Text = model.LocalFileName;
            autoGenerateDerivativeCheckBox.Checked = model.AutoGenerateDerivative == true;
            notesTextBox.Text = model.Notes;

            if (model.ProcessKind == ProcessKind.Ed)
            {
                processKindEdRadioButton.Checked = true;
            }
            else if (model.ProcessKind == ProcessKind.Fund)
            {
                processKindFundRadioButton.Checked = true;
            }
            else if (model.ProcessKind == ProcessKind.Kmf)
            {
                processKindKmfRadioButton.Checked = true;
            }
            else if (model.ProcessKind == ProcessKind.Raw)
            {
                processKindRawRadioButton.Checked = true;
            }
            else
            {
                processKindEdRadioButton.Checked = false;
                processKindKmfRadioButton.Checked = false;
                processKindFundRadioButton.Checked = false;
                processKindRawRadioButton.Checked = false;
            }

            if (_fileKindRequired)
            {
                if (model.FileKind == FileKind.Master)
                {
                    fileKindMasterRadioButton.Checked = true;
                }
                else if (model.FileKind == FileKind.Derivative)
                {
                    fileKindDerivativeRadioButton.Checked = true;
                }
                else if (model.FileKind == FileKind.Demo)
                {
                    fileKindDemoRadioButton.Checked = true;
                }
                else
                {
                    fileKindMasterRadioButton.Checked = false;
                    fileKindDerivativeRadioButton.Checked = false;
                    fileKindDemoRadioButton.Checked = false;
                }

                if (_masterFileIdRequired)
                {
                    await LoadMasterFilesForDocument();
                    SetMasterDocumentId(model.MasterDocumentId);
                }
            }

            _loading = false;
        }

        public async Task SaveToModel(string fileName, QueueItemModel model)
        {
            model.DocumentId = new Guid(documentIdTextBox.Text);
            model.LocalFileName = fileName; //fileNameTextBox.Text;

            model.Checksum = await ChecksumUtil.Calculate(model.LocalFileName);
            model.ProcessKind = RequireProcessKind();
            model.FileKind = _fileKindRequired ? (GetFileKind() ?? throw new Exception("Не е избран вид файл!")) : null;
            model.Size = new FileInfo(model.LocalFileName).Length;
            model.MasterDocumentId = _masterFileIdRequired ? GetMasterDocumentId() : null;
            model.AutoGenerateDerivative = _autoGenerateDerivativeVisible && autoGenerateDerivativeCheckBox.Checked;
            model.Notes = !string.IsNullOrWhiteSpace(notesTextBox.Text) ? notesTextBox.Text : null;

        }

